// Build the portable pass 21 before/after viewer (docs/review/ur-vfx-20261106/index.html).
// "Before" is main's renderer and VFX modules; other dependencies are checked before sharing src/.
// Textures are the runtime files the release embeds (optimized copies when they exist), inlined as data URLs.
//   node defense/scripts/review-ur-vfx.mjs [--base origin/main]
import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {execFileSync} from 'node:child_process';
import {build} from 'esbuild';
import {ASSET_PATHS,HERO,TRANSFORM_ART} from '../src/content.js';
import {RUNTIME_ASSET_PATHS} from '../src/asset-policy.js';
import {gameRoot,assetFile} from './local-inputs.mjs';
const args=process.argv.slice(2),base=args.includes('--base')?args[args.indexOf('--base')+1]:'origin/main',page=args.includes('--page')?args[args.indexOf('--page')+1]:'ur-vfx-20261106';
if(!page||page==='.'||page==='..'||/[/\\]/.test(page))throw new Error('Invalid review page folder');
const dir=path.join(gameRoot,'docs/review',page),beforeDir=path.join(dir,'before');
await fs.mkdir(beforeDir,{recursive:true});
// main's renderer files, with every import except each other resolved to the shared src/ copy.
const repoRoot=execFileSync('git',['rev-parse','--show-toplevel'],{cwd:gameRoot}).toString().trim();
const copies=['render.js','effects.js','ur-vfx.js'];
for(const name of copies){
  let text=execFileSync('git',['show',`${base}:defense/src/combat/${name}`],{cwd:repoRoot,maxBuffer:64<<20}).toString();
  // Paths are built from a prefix so this script itself has no out-of-game import-like string (tests/independence.test.mjs).
  const shared=['..','..','..','..','src'].join('/');
  text=text.replace(/from '\.\.\/([^']+)'/g,(m,file)=>`from '${shared}/${file}'`).replace(/from '\.\/([^']+)'/g,(m,file)=>copies.includes(file)?m:`from '${shared}/combat/${file}'`);
  await fs.writeFile(path.join(beforeDir,name),`// main (${base}) copy for the before column; generated by scripts/review-ur-vfx.mjs\n`+text);
}
// Only presentation payload additions are shared with main's renderer.
const allowedShared=new Map([
  ['combat/engine.js','shared scene engine adds only blast, radius, bonus and spent presentation event fields'],
  ['data.js','adds only the ur-kit3 asset path'],
]);
const srcDir=path.join(gameRoot,'src'),checked=new Set();
const guard={name:'before-dependency-guard',setup(b){
  b.onResolve({filter:/.*/},a=>({path:a.kind==='entry-point'?path.join(beforeDir,'render.js'):path.resolve(path.dirname(a.importer),a.path),namespace:'guard'}));
  b.onLoad({filter:/.*/,namespace:'guard'},async a=>{
    const text=await fs.readFile(a.path,'utf8'),relative=path.relative(srcDir,a.path).split(path.sep).join('/');
    if(!relative.startsWith('../')&&!checked.has(relative)){
      checked.add(relative);
      let original;try{original=execFileSync('git',['show',`${base}:defense/src/${relative}`],{cwd:repoRoot,maxBuffer:64<<20,stdio:['ignore','pipe','pipe']}).toString();}
      catch{throw new Error(`Before dependency missing from ${base}: defense/src/${relative}`);}
      if(original.replace(/\r\n/g,'\n')!==text.replace(/\r\n/g,'\n')&&!allowedShared.has(relative))throw new Error(`Before dependency differs from ${base}: defense/src/${relative}; copy it or explicitly allowlist it with a reason`);
    }
    return {contents:text,loader:'js'};
  });
}};
await build({entryPoints:['before-entry'],plugins:[guard],bundle:true,write:false,logLevel:'silent',define:{__GARDEN_SOLO__:'false',__GARDEN_UNLOCKED__:'false'}});
const manifest=JSON.parse(await fs.readFile(path.join(gameRoot,'docs/ASSET_OPTIMIZATION.json'),'utf8'));
const runtimePath=source=>{const mirrored=source.replace('./assets/','./assets/optimized/'),hit=manifest.images.find(i=>i.source===source&&i.output?.path===mirrored);return hit?hit.output.path:source;};
// Every runtime atlas except unit sheets, plus the units the fixtures place.
const {ROSTERS}=await import(pathToFileURL(path.join(dir,'scene.js')).href);
const heroes=new Set(Object.values(ROSTERS).flatMap(roster=>[...roster.deck,...roster.units.map(unit=>unit[1])]));
const unitAtlases=new Set([...Array.from(heroes,id=>{if(!HERO[id])throw new Error('Unknown roster hero: '+id);return HERO[id].art.atlas;}),...Object.values(TRANSFORM_ART).map(art=>art.atlas)]);
const ids=Object.keys(RUNTIME_ASSET_PATHS).filter(id=>!id.startsWith('unit-')||unitAtlases.has(id));
for(const id of unitAtlases)if(!ids.includes(id)){if(!ASSET_PATHS[id])throw new Error('Unknown unit atlas: '+id);ids.push(id);}
if(args.includes('--list'))console.log(ids.join('\n'));
const images={};
for(const id of ids){const file=assetFile(runtimePath(ASSET_PATHS[id]));images[id]='data:image/webp;base64,'+(await fs.readFile(file)).toString('base64');}
images['bright-garden']='data:image/webp;base64,'+(await fs.readFile(assetFile(runtimePath('./assets/bright/garden.webp')))).toString('base64');
// Resolve source files through Node so esbuild never enumerates protected ancestor directories.
const virtualFiles={name:'review-files',setup(b){
  b.onResolve({filter:/.*/},args=>({path:args.kind==='entry-point'?path.join(dir,'review.js'):path.resolve(path.dirname(args.importer),args.path),namespace:'review'}));
  b.onLoad({filter:/.*/,namespace:'review'},async args=>({contents:await fs.readFile(args.path,'utf8'),loader:'js'}));
}};
const bundle=await build({entryPoints:['review-entry'],plugins:[virtualFiles],bundle:true,write:false,format:'esm',target:['es2022'],minify:true,charset:'utf8',define:{__GARDEN_SOLO__:'false',__GARDEN_UNLOCKED__:'false'}});
const html=(await fs.readFile(path.join(dir,'template.html'),'utf8')).replace('/*__DATA__*/',()=>`window.UR_REVIEW_DATA=${JSON.stringify({images})};`).replace('/*__SCRIPT__*/',()=>bundle.outputFiles[0].text.replace(/<\/script/gi,'<\\/script'));
await fs.writeFile(path.join(dir,'index.html'),html.trimEnd()+'\n');
console.log(path.join(dir,'index.html')+' · '+(Buffer.byteLength(html)/1048576).toFixed(1)+' MB · '+ids.length+' textures');
