// Build the portable pass 21 before/after viewer (docs/review/ur-vfx-20261106/index.html).
// "Before" is main's render.js/effects.js (copied into before/ with imports pointed back at src/); "after" is this branch.
// Textures are the runtime files the release embeds (optimized copies when they exist), inlined as data URLs.
//   node defense/scripts/review-ur-vfx.mjs [--base origin/main]
import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {build} from 'esbuild';
import {ASSET_PATHS,HERO} from '../src/content.js';
import {RUNTIME_ASSET_PATHS} from '../src/asset-policy.js';
import {gameRoot,assetFile} from './local-inputs.mjs';
const args=process.argv.slice(2),base=args.includes('--base')?args[args.indexOf('--base')+1]:'origin/main';
const dir=path.join(gameRoot,'docs/review/ur-vfx-20261106'),beforeDir=path.join(dir,'before');
await fs.mkdir(beforeDir,{recursive:true});
// main's renderer files, with every import except each other resolved to the shared src/ copy.
const repoRoot=execFileSync('git',['rev-parse','--show-toplevel'],{cwd:gameRoot}).toString().trim();
for(const name of ['render.js','effects.js']){
  let text=execFileSync('git',['show',`${base}:defense/src/combat/${name}`],{cwd:repoRoot,maxBuffer:64<<20}).toString();
  // Paths are built from a prefix so this script itself has no out-of-game import-like string (tests/independence.test.mjs).
  const shared=['..','..','..','..','src'].join('/');
  text=text.replace(/from '\.\.\/([^']+)'/g,(m,file)=>`from '${shared}/${file}'`).replace(/from '\.\/([^']+)'/g,(m,file)=>['render.js','effects.js'].includes(file)?m:`from '${shared}/combat/${file}'`);
  await fs.writeFile(path.join(beforeDir,name),`// main (${base}) copy for the before column; generated by scripts/review-ur-vfx.mjs\n`+text);
}
const manifest=JSON.parse(await fs.readFile(path.join(gameRoot,'docs/ASSET_OPTIMIZATION.json'),'utf8'));
const runtimePath=source=>{const mirrored=source.replace('./assets/','./assets/optimized/'),hit=manifest.images.find(i=>i.source===source&&i.output?.path===mirrored);return hit?hit.output.path:source;};
// Every runtime atlas except unit sheets, plus the units the fixtures place.
const UNITS=['cherry_prince','luna','frost_witch','harmonious','jasmine','siren','queen','zeke','snow_rabbit','great_detective','flame_sage','guardian','storm_sage'];
const ids=Object.keys(RUNTIME_ASSET_PATHS).filter(id=>!id.startsWith('unit-')||UNITS.some(h=>HERO[h].art.atlas===id));
const images={};
for(const id of ids){const file=assetFile(runtimePath(ASSET_PATHS[id]));images[id]='data:image/webp;base64,'+(await fs.readFile(file)).toString('base64');}
images['bright-garden']='data:image/webp;base64,'+(await fs.readFile(assetFile(runtimePath('./assets/bright/garden.webp')))).toString('base64');
// Resolve source files through Node so esbuild never enumerates protected ancestor directories.
const virtualFiles={name:'review-files',setup(b){
  b.onResolve({filter:/.*/},args=>({path:args.kind==='entry-point'?path.join(dir,'review.js'):path.resolve(path.dirname(args.importer),args.path),namespace:'review'}));
  b.onLoad({filter:/.*/,namespace:'review'},async args=>({contents:await fs.readFile(args.path,'utf8'),loader:'js'}));
}};
const bundle=await build({entryPoints:['review-entry'],plugins:[virtualFiles],bundle:true,write:false,format:'esm',target:['es2022'],minify:true,charset:'utf8',define:{__GARDEN_SOLO__:'false',__GARDEN_UNLOCKED__:'false'}});
const html=(await fs.readFile(path.join(dir,'template.html'),'utf8')).replace('/*__DATA__*/',()=>`window.UR_REVIEW_DATA=${JSON.stringify({images})};`).replace('/*__SCRIPT__*/',()=>bundle.outputFiles[0].text.replace(/<\/script/gi,'<\\/script'));
await fs.writeFile(path.join(dir,'index.html'),html.trimEnd()+'\n');
console.log(path.join(dir,'index.html')+' · '+(Buffer.byteLength(html)/1048576).toFixed(1)+' MB · '+ids.length+' textures');
