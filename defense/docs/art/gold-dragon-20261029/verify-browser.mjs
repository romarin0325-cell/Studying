const NOW=Date.now(),deck=['gold_dragon','ancient_dragon','siren','time_magician','rumi'];
function fixture(side,opening){
  const p=createProfile(NOW);p.cleared=45;p.deck=deck;p.partner='gold_dragon';p.noticeLate=[...LATE_COMPANIONS];p.settings.auto=false;p.settings.sound=false;
  for(const id of deck)p.heroes[id].owned=true;p.heroes.gold_dragon.bond=10;
  assert.equal(command(p,'begin',{mode:'main',stage:46},NOW).ok,true);
  const s=createBattle(p),template=structuredClone(s.board.find(Boolean));s.board.fill(null);
  s.spawnIn=0;E.step(s,.01);s.queue=[];s.events=[];s.time=.01;s.waveTime=opening?.01:11.01;s.gauge=120;
  for(const [i,id] of [[12,'gold_dragon'],[0,'ancient_dragon'],[4,'siren'],[20,'time_magician'],[24,'rumi']])s.board[i]={...structuredClone(template),uid:s.nextId++,hero:id,rank:1,cooldown:id==='gold_dragon'?0:1e6,windup:0,attacks:0,born:-1};
  const e=s.enemies[0];Object.assign(e,{hp:1e8,maxHp:1e8,progress:side==='left'?1925:863,speed:0,skillIn:1e6});
  for(const offset of [-48,-24,24,48])s.enemies.push({...structuredClone(e),uid:s.nextId++,progress:e.progress+offset});
  p.active.run=E.serialize(s);assert.ok(validateProfile(p));assert.ok(resumeBattle(p));return p;
}
const browser=await chromium.launch({headless:true}),errors=[],network=[],results=[];
async function shot(page,label){
  const file=path.join(out,label+'.webp');await sharp(await page.screenshot({animations:'disabled'})).webp({quality:88}).toFile(file);
  const geometry=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,missing:[...document.images].filter(i=>i.offsetParent!==null&&(!i.complete||!i.naturalWidth)).map(i=>i.alt)}));
  assert.ok(geometry.scroll<=390,label+' horizontal overflow');assert.deepEqual(geometry.missing,[]);return {file:label+'.webp',geometry};
}
