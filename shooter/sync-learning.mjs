import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = path.dirname(fileURLToPath(import.meta.url));
const requested = process.argv[2];
let source = requested ? path.resolve(requested) : path.join(root,'../card/game');
try { await fs.access(path.join(source,'grammar_data.js')); } catch { if(requested) throw new Error('Card source missing'); source=path.join(root,'../card'); }
const definitions = [['vocab_data.js','VOCAB_SOURCE','vocab'],['collocation_data.js','COLLOCATION_DATA','collocation'],['grammar_data.js','GRAMMAR_DATA','grammar']];
const data = {}, provenance = [];
for(const [file,symbol,key] of definitions) {
  const code=await fs.readFile(path.join(source,file),'utf8');
  const context=vm.createContext({console});
  data[key]=vm.runInContext(`${code}\nJSON.parse(JSON.stringify(${symbol}));`,context,{timeout:5000});
  provenance.push({file,sha256:createHash('sha256').update(code).digest('hex'),entries:data[key].length});
}
for(const lecture of data.grammar) for(const q of lecture.quizzes || []) {
  if(!q.options.includes(q.answer) || !data.grammar.some(l=>l.id===q.lecture_id)) throw new Error(`Broken grammar source ${lecture.id}`);
}
await fs.mkdir(path.join(root,'learning'),{recursive:true});
await fs.writeFile(path.join(root,'learning/data.js'),`// Generated by sync-learning.mjs from Card source data. Do not edit manually.\nexport const LEARNING_DATA = ${JSON.stringify(data)};\n`);
await fs.writeFile(path.join(root,'learning/provenance.json'),JSON.stringify({source:'Card learning data',files:provenance},null,2)+'\n');
console.log(provenance);
