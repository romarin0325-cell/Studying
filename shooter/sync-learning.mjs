import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
const root = path.dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes('--check');
const requested = process.argv.slice(2).find(arg => arg !== '--check');
const source = requested ? path.resolve(requested) : path.join(root,'../card/game');
const definitions = [['vocab_data.js','VOCAB_SOURCE','vocab'],['collocation_data.js','COLLOCATION_DATA','collocation'],['grammar_data.js','GRAMMAR_DATA','grammar']];
const data = {}, provenance = [];
for(const [file,symbol,key] of definitions) {
  const code=await fs.readFile(path.join(source,file),'utf8');
  const context=vm.createContext({console});
  data[key]=vm.runInContext(`${code}\nJSON.parse(JSON.stringify(${symbol}));`,context,{timeout:5000});
  provenance.push({file,sha256:createHash('sha256').update(code).digest('hex'),entries:data[key].length});
}
for(const lecture of data.grammar) for(const q of lecture.quizzes || []) {
  if(!q.options.includes(q.answer) || !data.grammar.some(l=>l.id===q.lecture_id)) throw new Error(`Broken grammar source ${lecture.id}`);
}
const dataText = `// Generated by sync-learning.mjs from Card source data. Do not edit manually.\nexport const LEARNING_DATA = ${JSON.stringify(data)};\n`;
const provenanceText = JSON.stringify({source:'card/game (active Card source)',files:provenance},null,2)+'\n';
const normalizeEol = text => text.replace(/\r\n/g,'\n');
if(check) {
  const [currentData,currentProvenance] = await Promise.all([
    fs.readFile(path.join(root,'learning/data.js'),'utf8'),
    fs.readFile(path.join(root,'learning/provenance.json'),'utf8')
  ]);
  if(normalizeEol(currentData)!==dataText || normalizeEol(currentProvenance)!==provenanceText) {
    throw new Error('Shooter learning snapshot or provenance is out of sync. Run node shooter/sync-learning.mjs from the repository root.');
  }
  console.log('Learning snapshot matches active Card source:',provenance);
} else {
  await fs.mkdir(path.join(root,'learning'),{recursive:true});
  await Promise.all([
    fs.writeFile(path.join(root,'learning/data.js'),dataText),
    fs.writeFile(path.join(root,'learning/provenance.json'),provenanceText)
  ]);
  console.log('Learning snapshot regenerated:',provenance);
}
