// Audited motions use the original one-based roster slot, including inherited skills.
// extra.socket: the point on the sprite where the effect originates.
// extra.tint: element palette for the effect when the skill's own name says so (섀도우 → dark), else the caster's element.
function melee(expectedName, family, variant, frame, extra = {}) {
  return { expectedName, family, variant, range: 'melee', frame, ...extra };
}

function ranged(expectedName, family, variant, frame, socket, extra = {}) {
  return { expectedName, family, variant, range: 'ranged', frame, socket, ...extra };
}

